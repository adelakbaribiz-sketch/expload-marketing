async function main() {
  console.log('Seeding reseller opportunities...')

  for (const opp of opportunities) {
    const existing = await db.resellerOpportunity.findFirst({ where: { title: opp.title } })
    if (!existing) {
      // Fix the cons array issue (some entries have nested arrays)
      const cleanedOpp = {
        ...opp,
        cons: typeof opp.cons === 'string' ? opp.cons : JSON.stringify(opp.cons),
      }
      await db.resellerOpportunity.create({ data: cleanedOpp as any })
      console.log(`  ✓ Created: ${opp.title}`)
    } else {
      console.log(`  - Already exists: ${opp.title}`)
    }
  }

  console.log('\nDone!')
}

main().catch(console.error).finally(() => process.exit(0))
