// Round 3: Phased (Lowest start cost)
// Formula: 3 phases, pay-as-you-go, -60% start cost
// ============================================================================

class PhasedProposalState implements NegotiationStateHandler {
  readonly state = 'phased'
  readonly round = 3
  readonly type = 'phased'

  formulaDescription(): string {
    return 'Phased Delivery: Split into 3 independent phases, pay-per-phase, reduce initial cost by 60%.'
  }

  nextStateOnReject(): NegotiationState { return 'revenue_share' }

  async generateProposal(ctx: NegotiationContext): Promise<GeneratedProposal> {
    const initial = ctx.previousProposals.find(p => p.round === 0)
    if (!initial) throw new Error('Initial proposal missing')

    const phaseStartCost = initial.price * 0.40 // 60% reduction in starting cost

    const messages = buildPrompt(ctx, this, `
The customer REJECTED all previous proposals. Now generate a PHASED delivery plan:
- SPLIT the project into 3 independent phases, each delivering standalone value
- Phase 1: Foundation (MVP, usable end-to-end)
- Phase 2: Enhancement (advanced features)
- Phase 3: Polish & scale (optimization, integrations)
- Customer PAYS PER PHASE — only commits to Phase 1 upfront
- Phase 1 starting cost: $${phaseStartCost.toFixed(2)} (60% reduction from initial)
- Total across all 3 phases can equal or slightly exceed initial price
- Each phase has clear deliverables and acceptance criteria
- Customer can stop after any phase

This minimizes customer risk. Emphasize the low entry cost and flexibility.`)

    return callLlmAndParse(ctx, messages, this, {
      savingsPercent: 60, // initial start cost reduction
      deliveryReductionPercent: 0,
      scopeReductionPercent: 0,
    })
  }
}

