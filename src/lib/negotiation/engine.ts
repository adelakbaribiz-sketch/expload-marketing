const STATE_HANDLERS: Record<NegotiationState, NegotiationStateHandler | null> = {
  initial: new InitialProposalState(),
  mvp: new MvpProposalState(),
  economic: new EconomicProposalState(),
  phased: new PhasedProposalState(),
  revenue_share: new RevenueShareProposalState(),
  equity: new EquityProposalState(),
  accepted: null,
  rejected_all: null,
  closed: null,
}

/** Generate a proposal for the current state of the negotiation session. */
export async function generateProposalForSession(sessionId: string): Promise<{ proposal: any; state: NegotiationState }> {
  const session = await db.negotiationSession.findUnique({
    where: { id: sessionId },
    include: { proposals: { orderBy: { round: 'asc' } } },
  })
  if (!session) throw new Error('Negotiation session not found')

  const currentState = session.currentState as NegotiationState
  const handler = STATE_HANDLERS[currentState]
  if (!handler) throw new Error(`No proposal generation for state: ${currentState}`)

  const ctx: NegotiationContext = {
    sessionId: session.id,
    tenantId: session.tenantId,
    customerName: session.customerName,
    projectName: session.projectName,
    projectDescription: session.projectDescription,
    contextSummary: session.contextSummary,
    systemPrompt: session.systemPrompt ?? undefined,
    customerBudget: session.customerBudget ?? undefined,
    customerBudgetCurrency: session.customerBudgetCurrency,
    customerTimeline: session.customerTimeline ?? undefined,
    customerPriorities: session.customerPriorities ?? undefined,
    previousProposals: session.proposals.map(p => ({
      round: p.round, type: p.type, title: p.title,
      price: p.price, deliveryWeeks: p.deliveryWeeks,
      rejectionReason: p.customerFeedback ?? undefined,
    })),
  }

  // Generate
  const generated = await handler.generateProposal(ctx)

  // Persist
  const proposal = await db.negotiationProposal.create({
    data: {
      sessionId: session.id,
      round: handler.round,
      type: handler.type,
      title: generated.title,
      description: generated.description,
      features: JSON.stringify(generated.features),
      excludedFeatures: generated.excludedFeatures ? JSON.stringify(generated.excludedFeatures) : null,
      deliveryWeeks: generated.deliveryWeeks,
      price: generated.price,
      currency: generated.currency,
      paymentSchedule: generated.paymentSchedule,
      savingsPercent: generated.savingsPercent,
      deliveryReductionPercent: generated.deliveryReductionPercent,
      scopeReductionPercent: generated.scopeReductionPercent,
      customerResponse: 'pending',
    },
  })

  // Audit
  await db.negotiationAuditEvent.create({
    data: {
      sessionId: session.id,
      eventType: 'proposal_generated',
      round: handler.round,
      message: `Generated ${handler.type} proposal: ${generated.title} ($${generated.price})`,
      metadata: JSON.stringify({ round: handler.round, type: handler.type, price: generated.price }),
    },
  })

  // Notify
  await emitNotificationEvent({
    type: 'negotiation_proposal_ready',
    title: `New proposal ready: ${generated.title}`,
    message: `Round ${handler.round + 1}/${4} (${handler.type}): $${generated.price} · ${generated.deliveryWeeks} weeks`,
    severity: 'success',
    tenantId: session.tenantId,
    category: 'negotiation',
    actionUrl: `/negotiation/${session.id}`,
    metadata: { sessionId: session.id, proposalId: proposal.id, round: handler.round, type: handler.type },
  })

  return { proposal, state: currentState }
}

/** Process customer response — accept or reject a proposal. */
export async function respondToProposal(
  proposalId: string,
  response: 'accepted' | 'rejected',
  feedback?: string,
): Promise<{ newState: NegotiationState; nextProposalId?: string; allRejected: boolean }> {
  const proposal = await db.negotiationProposal.findUnique({
    where: { id: proposalId },
    include: { session: true },
  })
  if (!proposal) throw new Error('Proposal not found')

  // Update proposal
  await db.negotiationProposal.update({
    where: { id: proposalId },
    data: {
      customerResponse: response,
      customerFeedback: feedback,
      respondedAt: new Date(),
    },
  })

  const session = proposal.session
  const currentState = session.currentState as NegotiationState
  const handler = STATE_HANDLERS[currentState]

  if (response === 'accepted') {
    // Move to accepted state
    await db.negotiationSession.update({
      where: { id: session.id },
      data: {
        currentState: 'accepted',
        status: 'accepted',
        acceptedProposalId: proposalId,
      },
    })

    await db.negotiationAuditEvent.create({
      data: {
        sessionId: session.id,
        eventType: 'proposal_accepted',
        round: proposal.round,
        fromState: currentState,
        toState: 'accepted',
        message: `Proposal "${proposal.title}" accepted by customer`,
      },
    })

    await emitNotificationEvent({
      type: 'negotiation_accepted',
      title: 'Proposal accepted! 🎉',
      message: `Customer accepted proposal: ${proposal.title} ($${proposal.price}).`,
      severity: 'success',
      tenantId: session.tenantId,
      category: 'negotiation',
      actionUrl: `/negotiation/${session.id}`,
    })

    return { newState: 'accepted', allRejected: false }
  }

  // Rejected
  const nextState = handler?.nextStateOnReject() ?? 'rejected_all'

  // Persist rejection reasons
  const existingReasons = session.rejectionReasons ? JSON.parse(session.rejectionReasons) : []
  existingReasons.push({ round: proposal.round, type: proposal.type, reason: feedback ?? 'No reason given' })

  await db.negotiationSession.update({
    where: { id: session.id },
    data: {
      currentState: nextState,
      status: nextState === 'rejected_all' ? 'rejected_all' : 'active',
      rejectionReasons: JSON.stringify(existingReasons),
    },
  })

  await db.negotiationAuditEvent.create({
    data: {
      sessionId: session.id,
      eventType: 'proposal_rejected',
      round: proposal.round,
      fromState: currentState,
      toState: nextState,
      message: `Proposal "${proposal.title}" rejected. Reason: ${feedback ?? 'none'}`,
    },
  })

  if (nextState === 'rejected_all') {
    await emitNotificationEvent({
      type: 'negotiation_all_rejected',
      title: 'All proposals rejected',
      message: `Customer rejected all 4 proposals for "${session.projectName}". Session saved for manual follow-up.`,
      severity: 'critical',
      tenantId: session.tenantId,
      category: 'negotiation',
      actionUrl: `/negotiation/${session.id}`,
      metadata: { sessionId: session.id, rejectionReasons: existingReasons },
    })
    return { newState: 'rejected_all', allRejected: true }
  }

  // Auto-generate next proposal
  const { proposal: nextProposal } = await generateProposalForSession(session.id)
  return { newState: nextState, nextProposalId: nextProposal.id, allRejected: false }
}

// ============================================================================
// LLM Helpers
// ============================================================================

function buildPrompt(ctx: NegotiationContext, handler: NegotiationStateHandler, roundInstructions: string): LlmMessage[] {
  const sys: string = (ctx.systemPrompt ?? DEFAULT_SYSTEM_PROMPT) + `\n\n## Round Formula\n${handler.formulaDescription()}`

  const customerInfo = [
    `Customer: ${ctx.customerName}`,
    ctx.customerBudget ? `Budget: ${ctx.customerBudgetCurrency ?? 'USD'} ${ctx.customerBudget}` : '',
    ctx.customerTimeline ? `Timeline preference: ${ctx.customerTimeline}` : '',
    ctx.customerPriorities ? `Priorities: ${ctx.customerPriorities}` : '',
  ].filter(Boolean).join('\n')

  const prevProposals = ctx.previousProposals.length > 0
    ? ctx.previousProposals.map(p =>
        `  - Round ${p.round} (${p.type}): "${p.title}" — $${p.price}, ${p.deliveryWeeks}w. Rejection reason: ${p.rejectionReason ?? 'n/a'}`,
      ).join('\n')
    : '  (none — this is the first proposal)'

  const user = `# Project Brief
Name: ${ctx.projectName}
Description: ${ctx.projectDescription}

# Customer Context
${customerInfo}

# Background / Knowledge Base
${ctx.contextSummary.slice(0, 30000)}

# Previous Proposals
${prevProposals}

# Your Task (Round ${handler.round} — ${handler.type})
${roundInstructions}

# Output Format
Return STRICT JSON only (no markdown, no prose outside JSON):
{
  "title": "short compelling title",
  "description": "2-4 paragraph detailed description",
  "features": ["feature 1", "feature 2", "..."],
  "excludedFeatures": ["cut feature 1", "..."],  // empty array for initial
  "deliveryWeeks": 12,
  "price": 9500.00,
  "currency": "USD",
  "paymentSchedule": "50% upfront, 50% on delivery",
  "rationale": "1-2 sentence explanation of why this offer makes sense at this round"
}`

  return [
    { role: 'system', content: sys },
    { role: 'user', content: user },
  ]
}

const DEFAULT_SYSTEM_PROMPT = `You are a senior business development manager at a software agency.
You generate project proposals based on customer requirements and context.
Be realistic, specific, and customer-friendly. Always justify your pricing and timeline.
Prices should reflect fair market rates for software development ($50-150/hour blended rate).
Timeline should account for design, development, testing, and deployment.`

async function callLlmAndParse(
  ctx: NegotiationContext,
  messages: LlmMessage[],
  handler: NegotiationStateHandler,
  defaults: { savingsPercent: number; deliveryReductionPercent: number; scopeReductionPercent: number },
): Promise<GeneratedProposal> {
  const response = await llmAggregator.complete({
    messages,
    sessionType: 'negotiation',
    sessionId: ctx.sessionId,
    tenantId: ctx.tenantId,
    temperature: 0.7,
    maxTokens: 2048,
  })

  // Parse JSON — extract from markdown code blocks if present
  let text = response.text.trim()
  const jsonMatch = text.match(/```(?:json)?\s*([\s\S]*?)```/)
  if (jsonMatch) text = jsonMatch[1].trim()
  // Find first { and last }
  const start = text.indexOf('{')
  const end = text.lastIndexOf('}')
  if (start >= 0 && end > start) text = text.slice(start, end + 1)

  let parsed: any
  try {
    parsed = JSON.parse(text)
  } catch {
    throw new Error(`LLM returned invalid JSON: ${response.text.slice(0, 200)}`)
  }

  return {
    title: parsed.title ?? `${handler.type} proposal`,
    description: parsed.description ?? '',
    features: Array.isArray(parsed.features) ? parsed.features : [],
    excludedFeatures: Array.isArray(parsed.excludedFeatures) ? parsed.excludedFeatures : undefined,
    deliveryWeeks: Number(parsed.deliveryWeeks) || 12,
    price: Number(parsed.price) || 0,
    currency: parsed.currency ?? 'USD',
    paymentSchedule: parsed.paymentSchedule,
    savingsPercent: defaults.savingsPercent,
    deliveryReductionPercent: defaults.deliveryReductionPercent,
    scopeReductionPercent: defaults.scopeReductionPercent,
  }
}
