/**
 * Negotiation Engine — State Pattern.
 *
 * State machine for the 3-step fallback negotiation:
 *
 *   ┌─────────┐ reject  ┌─────┐ reject  ┌──────────┐ reject  ┌────────┐ reject  ┌──────────────┐
 *   │ initial │ ──────→ │ MVP │ ──────→ │ economic │ ──────→ │ phased │ ──────→ │ rejected_all │
 *   └─────────┘         └─────┘         └──────────┘         └────────┘         └──────────────┘
 *        │ accept           │ accept         │ accept              │ accept
 *        ▼                  ▼                ▼                     ▼
 *   ┌─────────────────────────────────────────────────────────────────────────────┐
 *   │ accepted                                                                     │
 *   └─────────────────────────────────────────────────────────────────────────────┘
 *
 * Proposal generation strategies (each round has its own formula):
 *  - Round 0 (Initial): Full scope, full price, full timeline.
 *  - Round 1 (MVP): Cut 20% scope, cut 30% timeline, cut 15% price.
 *  - Round 2 (Economic): Use cheaper LLM models, extend timeline 50%, cut 30% price.
 *  - Round 3 (Phased): Split into 3 phases, pay-as-you-go, cut 60% initial cost.
 *
 * All proposals are generated by the LLM Aggregator with round-specific prompts.
 */

import 'server-only'
import { db } from '@/lib/db'
import { llmAggregator } from '@/lib/llm/aggregator'
import { emitNotificationEvent } from '@/lib/notifications/emitter'
import { LlmMessage } from '@/lib/llm/types'

// ============================================================================
// States
// ============================================================================

export type NegotiationState = 'initial' | 'mvp' | 'economic' | 'phased' | 'revenue_share' | 'equity' | 'accepted' | 'rejected_all' | 'closed'

interface NegotiationContext {
  sessionId: string
  tenantId: string
  customerName: string
  projectName: string
  projectDescription: string
  contextSummary: string
  systemPrompt?: string
  customerBudget?: number
  customerBudgetCurrency?: string
  customerTimeline?: string
  customerPriorities?: string
  previousProposals: PreviousProposal[]
}

interface PreviousProposal {
  round: number
  type: string
  title: string
  price: number
  deliveryWeeks: number
  rejectionReason?: string
}

interface GeneratedProposal {
  title: string
  description: string
  features: string[]
  excludedFeatures?: string[]
  deliveryWeeks: number
  price: number
  currency: string
  paymentSchedule?: string
  savingsPercent: number
  deliveryReductionPercent: number
  scopeReductionPercent: number
}

// ============================================================================
// State Handlers (Strategy pattern per state)
// ============================================================================

interface NegotiationStateHandler {
  readonly state: NegotiationState
  readonly round: number
  readonly type: string  // 'initial' | 'mvp' | 'economic' | 'phased'
  /** Generate the proposal prompt + parse response. */
  generateProposal(ctx: NegotiationContext): Promise<GeneratedProposal>
  /** Next state if user rejects this proposal. */
  nextStateOnReject(): NegotiationState
  /** System prompt addition for this round (formula explanation). */
  formulaDescription(): string
}

// ============================================================================
// Round 0: Initial Proposal
// ============================================================================

class InitialProposalState implements NegotiationStateHandler {
  readonly state = 'initial'
  readonly round = 0
  readonly type = 'initial'

  formulaDescription(): string {
    return 'Full project scope with all requested features. Standard timeline and pricing.'
  }

  nextStateOnReject(): NegotiationState { return 'mvp' }

  async generateProposal(ctx: NegotiationContext): Promise<GeneratedProposal> {
    const messages = buildPrompt(ctx, this, `
Generate a COMPREHENSIVE initial proposal with:
- ALL requested features included (do not cut anything)
- Realistic full timeline (in weeks)
- Fair market price for the complete scope
- Standard payment schedule (50% upfront, 50% on delivery)
- Detailed description of what will be delivered
- List all features explicitly

Be specific and confident. This is the premium offer.`)

    return callLlmAndParse(ctx, messages, this, {
      savingsPercent: 0,
      deliveryReductionPercent: 0,
      scopeReductionPercent: 0,
    })
  }
}

// ============================================================================
// Round 1: MVP (Fast)
// Formula: -20% scope, -30% timeline, -15% price
// ============================================================================

class MvpProposalState implements NegotiationStateHandler {
  readonly state = 'mvp'
  readonly round = 1
  readonly type = 'mvp'

  formulaDescription(): string {
    return 'MVP Fast-Track: Cut 20% non-essential features, reduce delivery timeline by 30%, reduce price by 15% vs initial.'
  }

  nextStateOnReject(): NegotiationState { return 'economic' }

  async generateProposal(ctx: NegotiationContext): Promise<GeneratedProposal> {
    const initial = ctx.previousProposals.find(p => p.round === 0)
    if (!initial) throw new Error('Initial proposal missing')

    const reducedPrice = initial.price * 0.85
    const reducedWeeks = Math.max(1, Math.round(initial.deliveryWeeks * 0.70))

    const messages = buildPrompt(ctx, this, `
The customer REJECTED the initial proposal. Now generate a FAST MVP alternative:
- REMOVE ~20% of non-essential features (identify and explicitly exclude them)
- REDUCE delivery timeline by 30% (target: ${reducedWeeks} weeks)
- REDUCE price by 15% (target: $${reducedPrice.toFixed(2)})
- Focus on core value — what MUST be delivered to solve the customer's primary problem
- List excluded features explicitly so the customer sees what's being cut
- Payment: 40% upfront, 30% at midpoint, 30% on delivery

Be pragmatic. Emphasize speed-to-market.`)

    return callLlmAndParse(ctx, messages, this, {
      savingsPercent: 15,
      deliveryReductionPercent: 30,
      scopeReductionPercent: 20,
    })
  }
}

// ============================================================================
// Round 2: Economic
// Formula: Use cheaper LLM models, +50% timeline, -30% price
// ============================================================================

class EconomicProposalState implements NegotiationStateHandler {
  readonly state = 'economic'
  readonly round = 2
  readonly type = 'economic'

  formulaDescription(): string {
    return 'Economic: Use cost-optimized models (Llama 3 vs GPT-4), extend timeline by 50%, reduce price by 30% vs initial.'
  }

  nextStateOnReject(): NegotiationState { return 'phased' }

  async generateProposal(ctx: NegotiationContext): Promise<GeneratedProposal> {
    const initial = ctx.previousProposals.find(p => p.round === 0)
    if (!initial) throw new Error('Initial proposal missing')

    const reducedPrice = initial.price * 0.70
    const extendedWeeks = Math.round(initial.deliveryWeeks * 1.50)

    const messages = buildPrompt(ctx, this, `
The customer REJECTED the MVP proposal too. Now generate an ECONOMIC alternative:
- USE open-source / cost-optimized AI models (Llama 3, Mistral) instead of premium (GPT-4)
- KEEP most features but with simpler implementation (less custom AI, more off-the-shelf)
- EXTEND timeline by 50% (target: ${extendedWeeks} weeks)
- REDUCE price by 30% vs initial (target: $${reducedPrice.toFixed(2)})
- Same deliverable, just takes longer and uses cheaper building blocks
- Payment: 25% upfront, 25% per milestone, 25% on delivery

Be transparent about the trade-off: lower cost = longer timeline + standard components.`)

    return callLlmAndParse(ctx, messages, this, {
      savingsPercent: 30,
      deliveryReductionPercent: -50, // negative = increase
      scopeReductionPercent: 0,
    })
  }
}

